import os
import subprocess
import tempfile
from http.cookiejar import Cookie
from pathlib import Path
from typing import Iterable

import click

from storage.dto.user_cookies import SESSION_COOKIE_NAMES, normalize_cookie_expiry

from yagent.api_client import api_request


DEFAULT_DOMAINS = ("youtube.com",)
# Without an explicit profile yt-dlp reads whichever profile's cookie DB was
# written last, which flips between signed-in accounts from run to run.
CHROMIUM_BROWSERS = {"chrome", "chromium", "edge", "brave", "opera", "vivaldi", "whale"}
DEFAULT_CHROMIUM_PROFILE = "Default"


def _cookie_applies(cookie: Cookie, domain: str) -> bool:
    cookie_domain = (cookie.domain or "").lstrip(".").lower()
    domain = domain.lstrip(".").lower()
    return cookie_domain == domain or cookie_domain.endswith(f".{domain}")


def _format_bool(value: bool) -> str:
    return "TRUE" if value else "FALSE"


def _browser_cookie3_to_netscape(browser: str, domains: Iterable[str]) -> str:
    import browser_cookie3

    loaders = {
        "chrome": browser_cookie3.chrome,
        "chromium": getattr(browser_cookie3, "chromium", None),
        "firefox": browser_cookie3.firefox,
        "edge": getattr(browser_cookie3, "edge", None),
        "safari": getattr(browser_cookie3, "safari", None),
    }
    loader = loaders.get(browser)
    if loader is None:
        raise click.ClickException(f"Unsupported browser for fallback: {browser}")

    lines = ["# Netscape HTTP Cookie File", "# Generated by y cookies sync"]
    seen: set[tuple[str, str, str]] = set()
    for domain in domains:
        jar = loader(domain_name=domain)
        for cookie in jar:
            if not _cookie_applies(cookie, domain) or not cookie.name:
                continue
            key = (cookie.domain, cookie.path, cookie.name)
            if key in seen:
                continue
            seen.add(key)
            include_subdomains = cookie.domain_initial_dot or cookie.domain.startswith(".")
            expires = normalize_cookie_expiry(int(cookie.expires or 0))
            lines.append("\t".join([
                cookie.domain,
                _format_bool(include_subdomains),
                cookie.path or "/",
                _format_bool(bool(cookie.secure)),
                str(expires),
                cookie.name,
                cookie.value or "",
            ]))
    return "\n".join(lines) + "\n"


def _browser_spec(browser: str, profile: str | None) -> str:
    if profile is None and browser in CHROMIUM_BROWSERS:
        profile = DEFAULT_CHROMIUM_PROFILE
    return f"{browser}:{profile}" if profile else browser


def _extract_with_ytdlp(browser_spec: str) -> str:
    """Export the browser's full cookie jar via yt-dlp.

    Runs yt-dlp without a URL: it loads the browser jar, saves it on exit and
    then fails with a usage error, so no network request is made (a YouTube
    request stalled behind a slow proxy used to hit the timeout and lose the
    jar). The exit code is therefore ignored; only a written jar counts.
    Raises FileNotFoundError when yt-dlp is not installed.
    """
    fd, tmp_path = tempfile.mkstemp(prefix="y-cookies-", suffix=".txt")
    os.close(fd)
    Path(tmp_path).unlink(missing_ok=True)
    try:
        result = subprocess.run([
            "yt-dlp",
            "--cookies-from-browser", browser_spec,
            "--cookies", tmp_path,
            "--no-warnings",
        ], capture_output=True, text=True, timeout=60)
        path = Path(tmp_path)
        if not path.exists() or path.stat().st_size == 0:
            raise RuntimeError(result.stderr.strip() or f"yt-dlp exited {result.returncode} without writing cookies")
        return path.read_text(encoding="utf-8")
    finally:
        Path(tmp_path).unlink(missing_ok=True)


def _filter_netscape(cookies_txt: str, domain: str) -> str:
    lines = ["# Netscape HTTP Cookie File", "# Generated by y cookies sync"]
    normalized = domain.lstrip(".").lower()
    for raw_line in cookies_txt.splitlines():
        line = raw_line.strip()
        if not line or (line.startswith("#") and not line.startswith("#HttpOnly_")):
            continue
        parts = line.split("\t")
        if len(parts) < 7:
            continue
        cookie_domain = parts[0].removeprefix("#HttpOnly_").lstrip(".").lower()
        if cookie_domain == normalized or cookie_domain.endswith(f".{normalized}"):
            lines.append(line)
    return "\n".join(lines) + "\n"


def _cookie_names(cookies_txt: str) -> list[str]:
    return [
        line.split("\t")[5] for line in cookies_txt.splitlines()
        if line.strip()
        and (not line.startswith("#") or line.startswith("#HttpOnly_"))
        and len(line.split("\t")) >= 7
    ]


@click.command(name="sync")
@click.option("--domain", "domains", multiple=True, default=DEFAULT_DOMAINS, show_default=True, help="Cookie domain to sync; repeatable.")
@click.option("--browser", default="chrome", show_default=True, help="Browser for cookie extraction.")
@click.option("--profile", default=None, help=f"Browser profile name or path (Chromium browsers default to {DEFAULT_CHROMIUM_PROFILE!r}).")
def cookies_sync(domains: tuple[str, ...], browser: str, profile: str | None):
    """Sync local browser cookies to the y-agent API."""
    browser_spec = _browser_spec(browser, profile)
    click.echo(f"Exporting cookies from {browser_spec}", err=True)
    try:
        raw_cookies = _extract_with_ytdlp(browser_spec)
    except FileNotFoundError:
        # browser_cookie3 may miss signed-in cookies; only used without yt-dlp.
        click.echo("yt-dlp not found; falling back to browser_cookie3 (may miss signed-in cookies, ignores --profile)", err=True)
        raw_cookies = _browser_cookie3_to_netscape(browser, domains)
    except Exception as exc:
        raise click.ClickException(f"yt-dlp cookie export failed: {exc}")

    for domain in domains:
        cookies_txt = _filter_netscape(raw_cookies, domain)
        names = _cookie_names(cookies_txt)
        count = len(names)
        if count == 0:
            raise click.ClickException(f"No cookies found for {domain}")
        if domain.lstrip(".").lower() == "youtube.com" and not SESSION_COOKIE_NAMES & set(names):
            click.echo(
                f"Warning: no signed-in YouTube session cookies ({', '.join(sorted(SESSION_COOKIE_NAMES))}) "
                f"in the {browser_spec} export; check the browser profile is logged in",
                err=True,
            )
        resp = api_request("PUT", "/api/cookies", json={"domain": domain, "cookies_txt": cookies_txt})
        data = resp.json()
        click.echo(f"Synced {data.get('count', count)} cookies for {data.get('domain', domain)}")
